"use client";

import dynamic from "next/dynamic";
import { useEffect, useMemo, useRef, useState, type CSSProperties } from "react";
import { Moon, Sun } from "lucide-react";
import { Button } from "ui-lab-components/button";
import { Tabs } from "ui-lab-components/tabs";
import { useApp } from "@/features/theme/lib/app-context";
import { useNearViewport } from "@shared/lib/use-near-viewport";
import { Section, SectionHeading } from "./section";
import {
  resolveStyle,
  styles,
  type FamilyKey,
  type ResolvedStyle,
  type StyleKey,
  type ThemeMode,
} from "./token-styles";

/**
 * Layout
 * - Left: the claim, then every style as one visible picker. Each row carries its
 *   own palette as swatches, so the choice reads before it is made: pointing
 *   previews, pressing commits.
 * - Right: one dashboard screen under the active style's tokens, with the ramp
 *   that produced it directly beneath, so the screen and its source read together.
 * - The whole frame takes the active palette, so the swap reads as one coherent
 *   theme. Palettes are generated by the config route's generator and applied as
 *   inline variables on the frame only, the way `/config` scopes its preview.
 */

const TokensScreen = dynamic(() => import("./tokens-screen").then((module) => module.TokensScreen));

/** The screen is taller than its frame, so its bottom dissolves into the ramp. */
const screenFade = "linear-gradient(to bottom, #000 72%, transparent 100%)";

/** The three shades that identify a palette at a glance: ground, ink, accent. */
const signature = ["--background-900", "--foreground-100", "--accent-500"];

export function TokensSection() {
  const ref = useRef<HTMLDivElement>(null);
  const isNear = useNearViewport(ref);
  const { currentThemeMode, currentThemeColors } = useApp();
  const [styleKey, setStyleKey] = useState<StyleKey>("notion");
  const [hoveredKey, setHoveredKey] = useState<StyleKey | null>(null);
  const [family, setFamily] = useState<FamilyKey>("accent");
  // Until someone overrides it with the section's own toggle, the preview
  // follows the site theme, so flipping the site's light/dark switch is
  // reflected here too.
  const [mode, setMode] = useState<ThemeMode | null>(null);
  useEffect(() => {
    setMode(null);
  }, [currentThemeMode]);

  const activeMode = mode ?? currentThemeMode;
  // The picker shows every palette at once and the active one doubles as the
  // section's own theme, so all of them resolve together.
  const resolvedByKey = useMemo(
    () =>
      Object.fromEntries(
        styles.map((candidate) => {
          // "UI Lab" isn't a fixed brand palette like its neighbours — it stands
          // for the site's own theme, so it resolves from whatever the visitor
          // has actually configured rather than a hardcoded snapshot of it.
          const style =
            candidate.key === "ui-lab" && currentThemeColors
              ? {
                  ...candidate,
                  background: currentThemeColors.background,
                  foreground: currentThemeColors.foreground,
                  accent: currentThemeColors.accent,
                  accentChromaLimit: currentThemeColors.accentChromaLimit ?? candidate.accentChromaLimit,
                  globalAdjustments: currentThemeColors.globalAdjustments ?? candidate.globalAdjustments,
                }
              : candidate;
          return [candidate.key, resolveStyle(style, activeMode)];
        }),
      ) as Record<StyleKey, ResolvedStyle>,
    [activeMode, currentThemeColors],
  );

  // Pointing at a style only previews; the pressed one is what it falls back to.
  const activeKey = hoveredKey ?? styleKey;
  const resolved = resolvedByKey[activeKey];
  const groups = resolved.families.find((candidate) => candidate.key === family)?.groups ?? [];

  return (
    <Section ground="1000" rhythm="none" bleed>
      <div className="mx-auto w-full max-w-[1600px] p-2">
        <div
          ref={ref}
          className="grid overflow-hidden rounded-sm border border-background-700 bg-background-950 transition-colors duration-300 motion-reduce:transition-none lg:grid-cols-[minmax(0,0.34fr)_minmax(0,0.66fr)]"
          style={{ ...(resolved.vars as CSSProperties), colorScheme: activeMode }}
        >
          <div className="flex flex-col justify-between gap-12 border-b border-background-700 pb-6 lg:border-r lg:border-b-0">
            <SectionHeading
              size="small"
              title="You own the styles. Every surface, label, and accent resolves to your tokens."
            />

            <div className="flex flex-col gap-3 px-6">
              <div className="flex items-center justify-between">
                <span className="font-mono text-xs text-foreground-400">Style</span>
                {/* Same contract as a site theme toggle, scoped to the frame: only
                which block of token values applies changes. */}
                <Button
                  variant="secondary"
                  size="sm"
                  aria-label={activeMode === "dark" ? "Show in light mode" : "Show in dark mode"}
                  onPress={() => setMode(activeMode === "dark" ? "light" : "dark")}
                  icon={activeMode === "dark" ? <Moon size={13} /> : <Sun size={13} />}
                >
                  {activeMode === "dark" ? "Dark" : "Light"}
                </Button>
              </div>

              <div
                role="group"
                aria-label="Styles"
                className="flex flex-col overflow-hidden rounded-sm border border-background-700"
                onMouseLeave={() => setHoveredKey(null)}
              >
                {styles.map((candidate, index) => {
                  const selected = candidate.key === styleKey;
                  const vars = resolvedByKey[candidate.key].vars;
                  return (
                    <button
                      key={candidate.key}
                      type="button"
                      aria-pressed={selected}
                      onClick={() => setStyleKey(candidate.key)}
                      onMouseEnter={() => setHoveredKey(candidate.key)}
                      onFocus={() => setHoveredKey(candidate.key)}
                      onBlur={() => setHoveredKey(null)}
                      className={`flex cursor-pointer items-center gap-3 px-3 py-2.5 text-left text-sm transition-colors duration-200 hover:bg-background-900 focus-visible:bg-background-900 focus-visible:outline-none motion-reduce:transition-none ${index > 0 ? "border-t border-background-700" : ""} ${selected ? "bg-background-900 text-foreground-100" : "text-foreground-300"}`}
                    >
                      <span
                        aria-hidden
                        className="flex shrink-0 overflow-hidden rounded-xs border border-background-700"
                      >
                        {signature.map((name) => (
                          <span key={name} className="h-5 w-3" style={{ background: vars[name] }} />
                        ))}
                      </span>
                      <span className="flex-1 truncate">{candidate.label}</span>
                      {selected && <span aria-hidden className="h-1.5 w-1.5 rounded-full bg-accent-500" />}
                    </button>
                  );
                })}
              </div>
            </div>
          </div>

          <div className="flex min-w-0 flex-col">
            <figure
              className="relative h-[360px] overflow-hidden [--shot-scale:0.66] [--shot-x:6%] [--shot-y:8%] sm:h-[460px] sm:[--shot-scale:0.86] md:[--shot-scale:0.94] lg:h-[520px] lg:[--shot-scale:1] xl:[--shot-scale:1.1] 2xl:[--shot-scale:1.2]"
              style={{ maskImage: screenFade, WebkitMaskImage: screenFade }}
            >
              {/* The screen is inset from the frame's top-left corner, so the sizes
              take that offset back out and it still runs flush to the right and
              bottom edges. */}
              <div
                aria-hidden
                className="pointer-events-none absolute origin-top-left select-none bg-background-950"
                style={{
                  left: "var(--shot-x)",
                  top: "var(--shot-y)",
                  width: "calc((100% - var(--shot-x)) / var(--shot-scale))",
                  height: "calc((100% - var(--shot-y)) / var(--shot-scale))",
                  transform: "scale(var(--shot-scale))",
                }}
              >
                {isNear ? <TokensScreen /> : null}
              </div>
            </figure>

            <div className="flex flex-col gap-4 border-t border-background-700 p-4">
              <Tabs value={family} onValueChange={(value) => setFamily(value as FamilyKey)}>
                <Tabs.List aria-label="Token families">
                  {resolved.families.map((candidate) => (
                    <Tabs.Trigger key={candidate.key} value={candidate.key}>
                      {candidate.label}
                    </Tabs.Trigger>
                  ))}
                </Tabs.List>
              </Tabs>

              {/* Every family lays out as one row of ramps, so switching families
              never changes the panel's height. */}
              <div
                className={`grid gap-x-4 gap-y-3 ${groups.length > 1 ? "grid-cols-2 sm:grid-cols-4" : "grid-cols-1"}`}
              >
                {groups.map((group) => (
                  <div key={group.role} className="flex min-w-0 flex-col gap-2">
                    <span className="truncate font-mono text-xs text-foreground-400">
                      --{group.role}-*
                    </span>
                    <div className="flex gap-1">
                      {group.rows.map((row) => (
                        <div
                          key={row.name}
                          title={`--${row.name}: ${row.value}`}
                          className="flex min-w-0 flex-1 flex-col gap-1"
                        >
                          <span
                            className="h-10 rounded-xs border border-background-800"
                            style={{ background: row.value }}
                          />
                          <span className="font-mono text-[10px] text-foreground-400">{row.shade}</span>
                        </div>
                      ))}
                    </div>
                  </div>
                ))}
              </div>
            </div>
          </div>
        </div>
      </div>
    </Section>
  );
}
