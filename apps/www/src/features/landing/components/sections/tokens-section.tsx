"use client";

import dynamic from "next/dynamic";
import { Fragment, useEffect, useMemo, useRef, useState, type CSSProperties } from "react";
import { CircleAlert, Droplet, Layers, Moon, Palette, Sun, Type } from "lucide-react";
import { Button } from "ui-lab-components/button";
import { List } from "ui-lab-components/list";
import { Scroll } from "ui-lab-components/scroll";
import { Select } from "ui-lab-components/select";
import { useApp } from "@/features/theme/lib/app-context";
import { useNearViewport } from "@/shared/hooks/use-near-viewport";
import { Section, SectionHeading } from "./section";
import {
  resolveStyle,
  styles,
  type FamilyKey,
  type ResolvedStyle,
  type StyleKey,
  type ThemeMode,
} from "./token-styles";

/**
 * Mockup translation
 * - Left panel: a plain bordered frame (no window chrome in the mockup, so no `Shot`)
 *   holding the claim, the style pill, and the split box — `List` of token families
 *   beside every token that style generates.
 * - Right panel: the mockup's four tipped strips. Each is the same dashboard screen
 *   under a different product's tokens, so the four palettes stand side by side.
 *   Pointing at one grows it sideways and promotes its palette to the whole
 *   section — frame, pill, token list and every other strip — so the swap reads as
 *   one coherent theme rather than four unrelated swatches.
 * - The strips' palettes are generated by the config route's generator and applied as
 *   inline variables on the section only, the way `/config` scopes its preview.
 * - Added beside the pill: a light/dark toggle. The mockup shows one control, but the
 *   claim needs both halves of a theme, and it is the same swap a site toggle makes.
 * - Stars are the mockup's generic icon placeholder; each became the icon its row means.
 */

const TokensScreen = dynamic(() => import("./tokens-screen").then((module) => module.TokensScreen));

/** Left, right and bottom edges dissolve so the tipped strips have no cut-off seam. */
const fadeMask = [
  "linear-gradient(to right, transparent 0%, var(--background-950) 9%, var(--background-950) 91%, transparent 100%)",
  "linear-gradient(to bottom, #000 0%, #000 52%, transparent 100%)",
].join(", ");

/** Half the horizontal shift between a band's top and bottom edge, in percent. */
const BAND_TILT = 0;
/**
 * How far each band reaches back under its left neighbour, in percent. Two edges
 * animating towards the same seam can land a fraction of a pixel apart mid-flight
 * and flash the plane between them, so a seam is only ever one edge: the band on
 * top owns it, and the band beneath runs on underneath.
 */
const BAND_OVERLAP = 4;

/**
 * Band boundaries, one per hit-zone column. Every band keeps the same fixed slot
 * as the column that hovers it, so nothing shifts when the active band changes:
 * only the active band's own left edge moves, bleeding past the frame so it
 * covers every band before it. `BAND_OVERLAP` pulls each left edge back under
 * its neighbour, so the edges carry that offset forward and the painted seam
 * still lands on the column boundary.
 */
function bandEdgesFor(activeIndex: number) {
  const edges = styles.map((_, index) => (index / styles.length) * 100 + BAND_OVERLAP);
  // The first band has nothing to its left and the active one has to cover
  // everything before it, so both start off-frame.
  edges[0] = -100;
  edges[activeIndex] = -100;
  // The trailing edge runs past the frame too, so the tilt never exposes a corner.
  edges.push(200);
  return edges;
}

function bandClip(edges: number[], index: number) {
  const left = edges[index] - (index === 0 ? 0 : BAND_OVERLAP);
  const right = edges[index + 1];
  return `polygon(${left + BAND_TILT}% 0%, ${right + BAND_TILT}% 0%, ${right - BAND_TILT}% 100%, ${left - BAND_TILT}% 100%)`;
}

const familyIcons: Record<FamilyKey, typeof Palette> = {
  background: Layers,
  foreground: Type,
  accent: Droplet,
  status: CircleAlert,
};

export function TokensSection() {
  const ref = useRef<HTMLDivElement>(null);
  const isNear = useNearViewport(ref);
  const { currentThemeMode, currentThemeColors } = useApp();
  const [styleKey, setStyleKey] = useState<StyleKey>("notion");
  const [hoveredKey, setHoveredKey] = useState<StyleKey | null>(null);
  const [family, setFamily] = useState<FamilyKey>("background");
  // Until someone overrides it with the mockup's own toggle, the preview
  // follows the site theme, so flipping the site's light/dark switch is
  // reflected here too.
  const [mode, setMode] = useState<ThemeMode | null>(null);
  useEffect(() => {
    setMode(null);
  }, [currentThemeMode]);

  const activeMode = mode ?? currentThemeMode;
  // The four strips are the comparison, so every palette resolves at once and
  // the active one doubles as the section's own theme.
  const resolvedByKey = useMemo(
    () =>
      Object.fromEntries(
        styles.map((candidate) => {
          // "UI Lab" isn't a fixed brand palette like its neighbours — it stands
          // for the site's own theme, so it resolves from whatever the visitor
          // has actually configured rather than a hardcoded snapshot of it.
          const style =
            candidate.key === "ui-lab" && currentThemeColors
              ? {
                  ...candidate,
                  background: currentThemeColors.background,
                  foreground: currentThemeColors.foreground,
                  accent: currentThemeColors.accent,
                  accentChromaLimit: currentThemeColors.accentChromaLimit ?? candidate.accentChromaLimit,
                  globalAdjustments: currentThemeColors.globalAdjustments ?? candidate.globalAdjustments,
                }
              : candidate;
          return [candidate.key, resolveStyle(style, activeMode)];
        }),
      ) as Record<StyleKey, ResolvedStyle>,
    [activeMode, currentThemeColors],
  );

  // Hovering a strip only previews; the pill's choice is what it falls back to.
  const activeKey = hoveredKey ?? styleKey;
  const style = styles.find((candidate) => candidate.key === activeKey) ?? styles[0];
  const resolved = resolvedByKey[activeKey];
  const groups = resolved.families.find((candidate) => candidate.key === family)?.groups ?? [];
  const bandEdges = bandEdgesFor(styles.findIndex((candidate) => candidate.key === activeKey));

  return (
    <Section ground="1000" rhythm="none" bleed>
      <div className="mx-auto w-full max-w-[1600px] p-2">
        <div
          ref={ref}
          className="grid h-full overflow-hidden rounded-sm border border-background-700 bg-background-950 transition-colors duration-300 motion-reduce:transition-none lg:grid-cols-[minmax(0,0.35fr)_minmax(0,0.65fr)] lg:items-stretch"
          style={resolved.vars as CSSProperties}
        >
          <div className="flex flex-col">
            <div className="pt-12 pb-16">
              <SectionHeading
                size="small"
                title="You own the styles. Colour, spacing, and corners all resolve to your tokens."
              />
            </div>

            <div className="m-3 overflow-hidden">
              <div className="mb-2 border-background-700 flex items-center gap-2">
                <Select
                  selectedKey={styleKey}
                  label={style.label}
                  onSelectionChange={(key) => {
                    const nextStyle =
                      styles.find((candidate) => candidate.key === String(key)) ?? styles[0];
                    setStyleKey(nextStyle.key);
                  }}
                  className="w-full max-w-[10rem]"
                  styles={{ root: { style: resolved.vars as CSSProperties } }}
                >
                  <Select.Trigger icon={{ prefix: <Palette size={13} /> }}>
                    {style.label}
                  </Select.Trigger>
                  <Select.Content>
                    <Select.List>
                      {styles.map((candidate) => (
                        <Select.Item
                          key={candidate.key}
                          value={candidate.key}
                          textValue={candidate.label}
                        >
                          {candidate.label}
                        </Select.Item>
                      ))}
                    </Select.List>
                  </Select.Content>
                </Select>

                {/* Same contract as a site theme toggle, scoped to the screen: only
                which block of token values applies changes. */}
                <Button
                  variant="secondary"
                  size="sm"
                  aria-label={activeMode === "dark" ? "Show in light mode" : "Show in dark mode"}
                  onPress={() => setMode(activeMode === "dark" ? "light" : "dark")}
                  icon={activeMode === "dark" ? <Moon size={13} /> : <Sun size={13} />}
                >
                  {activeMode === "dark" ? "Dark" : "Light"}
                </Button>
              </div>

              <div className="grid border border-background-700 rounded-sm h-90 grid-cols-[minmax(0,0.50fr)_minmax(0,1fr)] overflow-hidden">
                <List
                  spacing="default"
                  aria-label="Token families"
                  className="max-w-none border-r gap-0 border-background-700"
                >
                  {resolved.families.map((candidate, index) => {
                    const Icon = familyIcons[candidate.key];
                    return (
                      <Fragment key={candidate.key}>
                        <List.Item
                          value={candidate.key}
                          selected={candidate.key === family}
                          onClick={() => setFamily(candidate.key)}
                          className="rounded-none px-1.5 py-2"
                        >
                          <List.Media className="size-6">
                            <Icon size={16} className="text-foreground-400" />
                          </List.Media>
                          <List.Title className="text-sm">{candidate.label}</List.Title>
                        </List.Item>
                        {index < resolved.families.length - 1 && <List.Divider spacing="none" />}
                      </Fragment>
                    );
                  })}
                </List>

                <Scroll className="h-full" maxHeight="100%" fade-y>
                  {groups.map((group) => (
                    <Fragment key={group.role}>
                      <div className="flex items-center gap-2 border-b border-background-700 px-3 py-2.5 font-mono text-xs">
                        <span className="text-foreground-300">{style.label}</span>
                        <span className="text-foreground-400">/</span>
                        <span className="text-foreground-400">{group.role}</span>
                      </div>
                      {group.rows.map((row) => (
                        <div
                          key={row.name}
                          className="flex items-center gap-2.5 border-b border-background-700 px-3 py-2.5 transition-colors duration-200 hover:bg-background-950 motion-reduce:transition-none"
                        >
                          <span
                            aria-hidden
                            className="h-7 w-7 shrink-0 rounded-xs border border-background-800"
                            style={{ background: row.value }}
                          />
                          <span className="truncate font-mono text-xs text-foreground-200">
                            {row.shade}
                          </span>
                          <span className="ml-auto shrink-0 font-mono text-xs text-foreground-400">
                            {row.value.replace(/^oklch\(|\)$/g, "")}
                          </span>
                        </div>
                      ))}
                    </Fragment>
                  ))}
                </Scroll>
              </div>
            </div>
          </div>

          <figure className="relative h-full overflow-hidden">
            <div
              className="absolute inset-0 [--shot-scale:0.66] [--shot-x:6%] [--shot-y:9%] sm:[--shot-scale:0.86] md:[--shot-scale:0.94] lg:[--shot-scale:1.03] xl:[--shot-scale:1.15] 2xl:[--shot-scale:1.25]"
              style={{
                maskImage: fadeMask,
                WebkitMaskImage: fadeMask,
                maskComposite: "intersect",
                WebkitMaskComposite: "source-in",
              }}
            >
              {/* Every band holds the same screen at the same size and the same
              place, and differs only in the tokens it resolves and the slice of it
              the clip lets through. Growing a band therefore moves a cut, never the
              content: the dashboard stays fixed while the palettes slide across it.
              The mockup's tilt lives in the clip polygon (offset one way at the top,
              the other at the bottom) rather than in a transform, so nothing the
              reader looks at is ever sheared, and each band overlaps the one to its
              left so a seam is a single animating edge that cannot come apart.

              This visual layer is purely decorative (`pointer-events-none`): the
              clip that grows a hovered band over its neighbours must never move
              the region the mouse is actually tracked against, or the boundary
              sliding under the cursor mid-hover would hand hover off to whichever
              band the pointer now sits over. Hit-testing lives in the fixed-width
              layer below instead. */}
              <div className="absolute inset-0 bg-background-950" onMouseLeave={() => setHoveredKey(null)}>
                {styles.map((candidate, index) => (
                  <div
                    key={candidate.key}
                    aria-hidden
                    className="pointer-events-none absolute inset-0 bg-background-950 transition-[clip-path] duration-500 ease-out motion-reduce:transition-none"
                    style={{
                      ...(resolvedByKey[candidate.key].vars as CSSProperties),
                      colorScheme: activeMode,
                      clipPath: bandClip(bandEdges, index),
                      // Each band's left border is its own shadow, so it follows the
                      // one edge that moves instead of being a strip that can widen.
                      filter: "drop-shadow(-1.5px 0 0 var(--background-600))",
                    }}
                  >
                    <div
                      className="absolute origin-top-left select-none"
                      style={{
                        background: "var(--background-950)",
                        // The screen is inset from the band's top-left corner, so the
                        // sizes take that offset back out and it still runs flush to
                        // the right and bottom edges.
                        left: "var(--shot-x)",
                        top: "var(--shot-y)",
                        width: "calc((100% - var(--shot-x)) / var(--shot-scale))",
                        height: "calc((100% - var(--shot-y)) / var(--shot-scale))",
                        transform: "scale(var(--shot-scale))",
                      }}
                    >
                      {isNear ? <TokensScreen /> : null}
                    </div>
                  </div>
                ))}

                {/* Hit zones: one fixed-width, non-overlapping column per style,
                always at the same place regardless of what's hovered. Only the
                decorative layer above grows; the hoverable/clickable area never
                does, so the target under the cursor can't change mid-hover. */}
                {styles.map((candidate, index) => (
                  <div
                    key={candidate.key}
                    role="button"
                    tabIndex={0}
                    aria-label={`Preview the ${candidate.label} palette`}
                    aria-pressed={candidate.key === styleKey}
                    onClick={() => setStyleKey(candidate.key)}
                    onKeyDown={(event) => {
                      if (event.key === "Enter" || event.key === " ") {
                        event.preventDefault();
                        setStyleKey(candidate.key);
                      }
                    }}
                    onMouseEnter={() => setHoveredKey(candidate.key)}
                    onFocus={() => setHoveredKey(candidate.key)}
                    onBlur={() => setHoveredKey(null)}
                    className="absolute inset-y-0 cursor-pointer"
                    style={{
                      left: `${(index / styles.length) * 100}%`,
                      width: `${100 / styles.length}%`,
                    }}
                  />
                ))}
              </div>
            </div>
          </figure>
        </div>
      </div>
    </Section>
  );
}
